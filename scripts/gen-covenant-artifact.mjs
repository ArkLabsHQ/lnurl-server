import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fetchArkadec } from "./get-arkadec.mjs";

const SRC = resolve("contracts/forwarding.ark");
const ARTIFACT = resolve("contracts/forwarding.json");
const MODULE = resolve("src/covenant/forwarding-artifact.ts");
const bin = await fetchArkadec();
const scratch = mkdtempSync(join(tmpdir(), "lnurl-covenant-"));
try {
  const raw = join(scratch, "forwarding.json");
  execFileSync(bin, [SRC, "-o", raw], { stdio: "inherit" });
  const artifact = JSON.parse(readFileSync(raw, "utf8"));
  delete artifact.updatedAt;
  writeFileSync(ARTIFACT, `${JSON.stringify(artifact, null, 2)}\n`);
  const { contractName, constructorInputs, functions } = artifact;
  writeFileSync(MODULE, [
    "// Generated by scripts/gen-covenant-artifact.mjs; regenerate with pnpm artifact.",
    `export const FORWARDING_ARTIFACT = ${JSON.stringify({ contractName, constructorInputs, functions }, null, 2)};`,
    "",
  ].join("\n"));
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
console.log(`wrote ${ARTIFACT}\nwrote ${MODULE}`);
